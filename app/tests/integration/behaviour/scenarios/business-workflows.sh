# Scenarios for openspec/specs/business-workflows/spec.md

Scenario "Add a vehicle and sell it"
  Given "the sample showroom data"
  And   "I add a vehicle with plate \"AB12 CDE\" and list price \"6500.00\""
  When  "I sell vehicle 1013 to customer 2001"
  Then  "invoice 50233 is saved with list \"6500.00\""
  When  "I list stock"
  Then  "the screen does not show \"AB12 CDE\""
  When  "I list all vehicles"
  Then  "the line for \"1013\" shows \"SOLD\""

Scenario "Reserve a vehicle and sell it"
  Given "the sample showroom data"
  And   "I reserve or release vehicle 1002"
  When  "I sell vehicle 1002 to customer 2001"
  Then  "the screen shows \"Invoice 50233 created.\""
  When  "I list all vehicles"
  Then  "the line for \"1002\" shows \"SOLD\""

Scenario "Reserve, release and sell a vehicle"
  Given "the sample showroom data"
  And   "I reserve or release vehicle 1002"
  And   "I reserve or release vehicle 1002"
  When  "I sell vehicle 1002 to customer 2001"
  Then  "the screen shows \"Invoice 50233 created.\""
  When  "I list all vehicles"
  Then  "the line for \"1002\" shows \"SOLD\""

Scenario "Nothing further can happen to a sold vehicle"
  Given "the sample showroom data"
  And   "I sell vehicle 1002 to customer 2001"
  When  "I reserve or release vehicle 1002"
  Then  "the screen shows \"Vehicle is already sold.\""
  When  "I try to quote vehicle 1002"
  Then  "the screen shows \"Vehicle is already sold.\""
  When  "I try to sell vehicle 1002"
  Then  "the screen shows \"Vehicle is already sold.\""

Scenario "Add a customer and sell to them"
  Given "the sample showroom data"
  And   "I add a customer with name \"New Buyer\""
  When  "I sell vehicle 1002 to customer 2009"
  And   "I list invoices"
  Then  "the line for \"50233\" shows \"New Buyer\""

Scenario "Price changes between quote and sale"
  Given "the sample showroom data"
  And   "I quote vehicle 1002 for customer 2001"
  When  "I change the price of vehicle 1002 to \"11250.50\""
  And   "I sell vehicle 1002 to customer 2001"
  Then  "invoice 50233 is saved with list \"11250.50\""

Scenario "Cancelled sale leaves the vehicle available"
  Given "the sample showroom data"
  And   "I answer \"N\" to selling vehicle 1002 to customer 2001"
  When  "I sell vehicle 1002 to customer 2002"
  Then  "the screen shows \"Invoice 50233 created.\""

Scenario "Invoice unchanged by a price change and a restart"
  Given "the sample showroom data"
  And   "I sell vehicle 1002 to customer 2001"
  When  "I change the price of vehicle 1002 to \"1\""
  And   "the app is restarted"
  And   "I view invoice 50233"
  Then  "the total is 13429.00"
