# Scenarios for openspec/specs/data-files/spec.md

Scenario "Started from the application folder"
  Given "the sample showroom data"
  When  "I list stock"
  Then  "the screen shows \"9 vehicle(s)\""

Scenario "Pipe typed into a field"
  Given "the sample showroom data"
  When  "I add a customer with name \"A|B Ltd\""
  Then  "customer 2009 is saved with name \"A/B Ltd\""

Scenario "Windows line endings"
  Given "the sample showroom data"
  And   "the stock file has CRLF line endings"
  When  "I list stock"
  Then  "the screen shows \"9 vehicle(s)\""

Scenario "Vehicle added"
  Given "the sample showroom data"
  When  "I add a vehicle with plate \"AB12 CDE\""
  Then  "stock.dat contains \"1013|AB12 CDE|\""
  And   "next_ids.dat contains \"vehicle=1014\""

Scenario "Added vehicle after a restart"
  Given "the sample showroom data"
  And   "I add a vehicle with plate \"AB12 CDE\""
  When  "the app is restarted"
  And   "I search for plate \"AB12 CDE\""
  Then  "the screen shows \"ID       : 1013\""

Scenario "Added customer after a restart"
  Given "the sample showroom data"
  And   "I add a customer with name \"New Customer Ltd\""
  When  "the app is restarted"
  And   "I search customers for \"New Customer Ltd\""
  Then  "the screen shows \"1 match(es)\""

Scenario "Changed price after a restart"
  Given "the sample showroom data"
  And   "I change the price of vehicle 1002 to \"11250.50\""
  When  "the app is restarted"
  And   "I search for plate \"yf20 hbn\""
  Then  "the screen shows \"Price    : 11250.50\""

Scenario "Reservation after a restart"
  Given "the sample showroom data"
  And   "I reserve or release vehicle 1002"
  When  "the app is restarted"
  And   "I search for plate \"yf20 hbn\""
  Then  "the screen shows \"Status   : RESERVED\""

Scenario "Sale after a restart"
  Given "the sample showroom data"
  And   "I sell vehicle 1002 to customer 2001"
  When  "the app is restarted"
  And   "I try to quote vehicle 1002"
  Then  "the screen shows \"Vehicle is already sold.\""

Scenario "Vehicle ids after a restart"
  Given "the sample showroom data"
  And   "I add a vehicle"
  When  "the app is restarted"
  And   "I add a vehicle with plate \"ZZ02 ZZZ\""
  Then  "the screen shows \"Vehicle 1014 added.\""

Scenario "Customer ids after a restart"
  Given "the sample showroom data"
  And   "I add a customer"
  When  "the app is restarted"
  And   "I add a customer with name \"Second Customer\""
  Then  "the screen shows \"Customer 2010 added.\""

Scenario "Invoice numbers after a restart"
  Given "the sample showroom data"
  And   "I sell vehicle 1002 to customer 2001"
  When  "the app is restarted"
  And   "I sell vehicle 1003 to customer 2001"
  Then  "the screen shows \"Invoice 50234 created.\""
