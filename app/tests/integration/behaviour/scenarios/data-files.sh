# Scenarios for openspec/specs/data-files/spec.md

Scenario "Started from the application folder"
  Given "the sample showroom data"
  When  "I list stock"
  Then  "the screen shows \"9 vehicle(s)\""

Scenario "Pipe typed into a field"
  Given "the sample showroom data"
  When  "I add a customer with name \"A|B Ltd\""
  Then  "customer 2009 is saved with name \"A/B Ltd\""

Scenario "Windows line endings"
  Given "the sample showroom data"
  And   "the stock file has CRLF line endings"
  When  "I list stock"
  Then  "the screen shows \"9 vehicle(s)\""

Scenario "Vehicle added"
  Given "the sample showroom data"
  When  "I add a vehicle with plate \"AB12 CDE\""
  Then  "stock.dat contains \"1013|AB12 CDE|\""
  And   "next_ids.dat contains \"vehicle=1014\""

Scenario "Added vehicle after a restart"
  Given "the sample showroom data"
  And   "I add a vehicle with plate \"AB12 CDE\""
  When  "the app is restarted"
  And   "I search for plate \"AB12 CDE\""
  Then  "the screen shows \"ID       : 1013\""

Scenario "Added customer after a restart"
  Given "the sample showroom data"
  And   "I add a customer with name \"New Customer Ltd\""
  When  "the app is restarted"
  And   "I search customers for \"New Customer Ltd\""
  Then  "the screen shows \"1 match(es)\""

Scenario "Changed price after a restart"
  Given "the sample showroom data"
  And   "I change the price of vehicle 1002 to \"11250.50\""
  When  "the app is restarted"
  And   "I search for plate \"yf20 hbn\""
  Then  "the screen shows \"Price    : 11250.50\""

Scenario "Reservation after a restart"
  Given "the sample showroom data"
  And   "I reserve or release vehicle 1002"
  When  "the app is restarted"
  And   "I search for plate \"yf20 hbn\""
  Then  "the screen shows \"Status   : RESERVED\""

Scenario "Sale after a restart"
  Given "the sample showroom data"
  And   "I sell vehicle 1002 to customer 2001"
  When  "the app is restarted"
  And   "I try to quote vehicle 1002"
  Then  "the screen shows \"Vehicle is already sold.\""

Scenario "Vehicle ids after a restart"
  Given "the sample showroom data"
  And   "I add a vehicle"
  When  "the app is restarted"
  And   "I add a vehicle with plate \"ZZ02 ZZZ\""
  Then  "the screen shows \"Vehicle 1014 added.\""

Scenario "Customer ids after a restart"
  Given "the sample showroom data"
  And   "I add a customer"
  When  "the app is restarted"
  And   "I add a customer with name \"Second Customer\""
  Then  "the screen shows \"Customer 2010 added.\""

Scenario "Invoice numbers after a restart"
  Given "the sample showroom data"
  And   "I sell vehicle 1002 to customer 2001"
  When  "the app is restarted"
  And   "I sell vehicle 1003 to customer 2001"
  Then  "the screen shows \"Invoice 50234 created.\""

Scenario "Stock file missing"
  Given "the sample showroom data without stock.dat"
  When  "I list stock"
  Then  "the screen shows \"0 vehicle(s)\""

Scenario "Customer file missing"
  Given "the sample showroom data without customers.dat"
  When  "I list customers"
  Then  "the screen shows \"0 customer(s)\""

Scenario "Invoice file missing"
  Given "the sample showroom data without invoices.dat"
  When  "I list invoices"
  Then  "the screen shows \"0 invoice(s)\""

Scenario "Missing file is created on save"
  Given "the sample showroom data without customers.dat"
  When  "I add a customer with name \"First Customer\""
  Then  "customers.dat contains \"First Customer\""

Scenario "Customer record with fields missing"
  Given "the sample showroom data"
  And   "the customer file also holds \"2100|Short\""
  When  "I list customers"
  Then  "the line for \"2100\" shows \"Retail\""

Scenario "Vehicle record with fields missing"
  Given "the sample showroom data"
  And   "the stock file also holds \"1100|S1\""
  When  "I list all vehicles"
  Then  "the line for \"1100\" shows \"0.00\""
  And   "the line for \"1100\" shows \"IN STOCK\""

Scenario "Unknown customer type"
  Given "the sample showroom data"
  And   "the customer file also holds \"2101|Odd|1|a@example.com|X\""
  When  "I list customers"
  Then  "the line for \"2101\" shows \"Retail\""

Scenario "Unknown vehicle status"
  Given "the sample showroom data"
  And   "the stock file also holds \"1101|S2|Ford|Focus|2020|1|1.00|2.00|7\""
  When  "I list all vehicles"
  Then  "the line for \"1101\" shows \"?\""

Scenario "Windows line endings removed by a save"
  Given "the sample showroom data"
  And   "the stock file has CRLF line endings"
  When  "I change the price of vehicle 1002 to \"9\""
  Then  "stock.dat has no CRLF line endings"

Scenario "Blank lines and comments are skipped on load"
  Given "the sample showroom data"
  And   "the customer file has a blank line and a comment"
  When  "I list customers"
  Then  "the screen shows \"8 customer(s)\""

Scenario "Marking a customer changes only that record"
  Given "the sample showroom data"
  When  "I mark customer 2008 as a fleet customer"
  Then  "only record 2008 of customers.dat has changed"

Scenario "Known bug: BUG-001 blank make loses the price"
  Given "the sample showroom data"
  And   "I add a vehicle with plate \"ZZ2\" and make \"\" and list price \"2000.00\""
  When  "the app is restarted"
  And   "I search for plate \"ZZ2\""
  Then  "the screen shows \"Price    : 0.00\""
  And   "the screen shows \"Vehicle  : Focus 2020 (1000)\""

Scenario "Known bug: BUG-001 blank model loses the price"
  Given "the sample showroom data"
  And   "I add a vehicle with plate \"ZZ3\" and model \"\" and list price \"2000.00\""
  When  "the app is restarted"
  And   "I search for plate \"ZZ3\""
  Then  "the screen shows \"Price    : 0.00\""
  And   "the screen shows \"Vehicle  : Ford 2020 (1000)\""

Scenario "Known bug: BUG-001 vehicle sold at the lost price"
  Given "the sample showroom data"
  And   "I add a vehicle with plate \"ZZ2\" and make \"\" and list price \"2000.00\""
  When  "the app is restarted"
  And   "I sell vehicle 1013 to customer 2001"
  Then  "the list price is 0.00"
  And   "the total is 235.00"

Scenario "Known bug: BUG-006 duplicate vehicle id"
  Given "the sample showroom data without next_ids.dat"
  And   "I add a vehicle with plate \"A1\""
  When  "I add a vehicle with plate \"A2\""
  Then  "the screen shows \"Vehicle 1001 added.\""
  And   "stock.dat has a duplicate id 1001"

Scenario "Known bug: BUG-007 app starts empty"
  Given "a folder with no data folder"
  When  "I list stock"
  Then  "the screen shows \"0 vehicle(s)\""
  And   "the screen does not show \"ERROR\""

Scenario "Known bug: BUG-007 failed save reported as added"
  Given "a folder with no data folder"
  When  "I add a vehicle"
  Then  "the screen shows \"ERROR: cannot write next_ids.dat\""
  And   "the screen shows \"Vehicle 1000 added.\""

Scenario "Known bug: BUG-008 save drops vehicles over the limit"
  Given "a stock file holding 510 vehicles"
  When  "I change the price of vehicle 3000 to \"9\""
  Then  "stock.dat holds 500 records"

Scenario "Known bug: BUG-013 comment lost on save"
  Given "the sample showroom data"
  And   "the stock file has a comment"
  When  "I change the price of vehicle 1002 to \"9\""
  Then  "stock.dat does not contain \"# a note\""
