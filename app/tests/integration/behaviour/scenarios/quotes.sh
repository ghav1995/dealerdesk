# Scenarios for openspec/specs/quotes/spec.md

Scenario "Unknown vehicle"
  Given "the sample showroom data"
  When  "I try to quote vehicle 9999"
  Then  "the screen shows \"Vehicle not found.\""
  And   "the screen does not show \"Customer ID\""

Scenario "Sold vehicle stops the quote"
  Given "the sample showroom data"
  When  "I try to quote vehicle 1001"
  Then  "the screen shows \"Vehicle is already sold.\""
  And   "the screen does not show \"Customer ID\""

Scenario "Unknown customer"
  Given "the sample showroom data"
  When  "I try to quote vehicle 1002 for customer 9999"
  Then  "the screen shows \"Customer not found.\""
  And   "the screen does not show \"Discount %\""

Scenario "Retail quote heading"
  Given "the sample showroom data"
  When  "I quote vehicle 1002 for customer 2001"
  Then  "the screen shows \"QUOTATION (valid 7 days)\""
  And   "the screen shows \"Customer : Sarah Whitfield (Retail)\""
  And   "the screen shows \"Vehicle  : yf20 hbn Vauxhall Corsa 1.2 SE\""

Scenario "Trade quote heading"
  Given "the sample showroom data"
  When  "I quote vehicle 1004 for customer 2002"
  Then  "the screen shows \"Customer : Marlow Motors Ltd (Trade)\""

Scenario "Quote lines"
  Given "the sample showroom data"
  When  "I quote vehicle 1002 for customer 2001 with no discount and no trade-in"
  Then  "the list price is 10995.00"
  And   "the net price is 10995.00"
  And   "the delivery is 150.00"
  And   "the VAT is 2229.00"
  And   "the registration fee is 55.00"
  And   "the total is 13429.00"

Scenario "No optional lines"
  Given "the sample showroom data"
  When  "I quote vehicle 1002 for customer 2001 with no discount and no trade-in"
  Then  "there is no trade discount line"
  And   "there is no fleet discount line"
  And   "there is no discount line"
  And   "there is no trade-in line"

Scenario "All optional lines"
  Given "the sample showroom data"
  When  "I quote vehicle 1004 for customer 2002 with 10% discount and 500.00 trade-in"
  Then  "the trade discount is -1675.00"
  And   "the screen shows \"Discount (10.0%)\""
  And   "the discount is -1507.50"
  And   "the trade-in is -500.00"

Scenario "Data unchanged after a quote"
  Given "the sample showroom data"
  When  "I quote vehicle 1002 for customer 2001 with 5% discount and 1000.00 trade-in"
  Then  "the data files are unchanged"

Scenario "Same vehicle quoted twice"
  Given "the sample showroom data"
  When  "I quote vehicle 1002 for customer 2001"
  Then  "the total is 13429.00"
  When  "I quote vehicle 1002 for customer 2002"
  Then  "the trade discount is -1099.50"
  And   "vehicle 1002 is saved with status \"0\""

Scenario "Fleet quote heading"
  Given "the sample showroom data"
  And   "I mark customer 2008 as a fleet customer"
  When  "I quote vehicle 1002 for customer 2008"
  Then  "the screen shows \"Customer : Greenway Taxis (Fleet)\""

Scenario "Fleet discount line"
  Given "the sample showroom data"
  And   "I mark customer 2008 as a fleet customer"
  When  "I quote vehicle 1002 for customer 2008"
  Then  "the fleet discount is -439.80"
  And   "the \"Fleet discount\" line is between \"List price\" and \"Net price\""
  And   "there is no trade discount line"
